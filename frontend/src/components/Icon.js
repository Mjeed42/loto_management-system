const Icon = ({
  name,
  size = "md",
  className = "",
  color = "currentColor",
  animate = false,
  ...props
}) => {
  const icon = SVGIcons[name];

  if (!icon) {
    console.warn(
      `Icon "${name}" not found. Available icons:`,
      Object.keys(SVGIcons)
    );
    return <span className={`${className} text-muted`} {...props}></span>;
  }

  const sizeClasses = {
    xs: "w-3 h-3",
    sm: "w-4 h-4",
    md: "w-5 h-5",
    lg: "w-6 h-6",
    xl: "w-8 h-8",
  };

  const sizeClass = sizeClasses[size] || sizeClasses.md;
  const animateClass = animate ? "animate-spin" : "";

  const iconStyle = {
    width:
      size === "xs"
        ? "12px"
        : size === "sm"
        ? "16px"
        : size === "md"
        ? "20px"
        : size === "lg"
        ? "24px"
        : size === "xl"
        ? "32px"
        : "20px",
    height:
      size === "xs"
        ? "12px"
        : size === "sm"
        ? "16px"
        : size === "md"
        ? "20px"
        : size === "lg"
        ? "24px"
        : size === "xl"
        ? "32px"
        : "20px",
    color: color,
    display: "inline-flex",
    verticalAlign: "middle",
  };

  return (
    <span
      className={`${animateClass} ${className}`}
      style={iconStyle}
      role="img"
      aria-label={name}
      {...props}
    >
      {icon}
    </span>
  );
};

export default Icon;
